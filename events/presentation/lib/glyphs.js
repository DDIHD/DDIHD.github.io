const SPELLED = { Ä: 'AE', Ö: 'OE', Ü: 'UE', ß: 'SS' }

/** Upper-case, spell out umlauts, drop characters the font does not know. */
export function normalizeText(text) {
  return String(text)
    .toUpperCase()
    .replace(/[ÄÖÜß]/g, (ch) => SPELLED[ch])
    .split('')
    .filter((ch) => GLYPHS[ch])
    .join('')
}
